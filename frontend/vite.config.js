import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";

export default defineConfig({
  plugins: [react()],
  server: {
    fs: {
      // Permite importar content/ (fuente única de verdad) desde fuera de frontend/
      allow: [import.meta.dirname, ".."],
    },
    proxy: {
      // En desarrollo, las rutas /api/* van al backend FastAPI
      "/api": {
        target: "http://127.0.0.1:8000",
        changeOrigin: true,
      },
    },
  },
  build: {
    rollupOptions: {
      output: {
        manualChunks(id) {
          if (id.includes("node_modules")) return "vendor";
          return undefined;
        },
      },
    },
  },
});
